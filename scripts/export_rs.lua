-- Exports the Lua data tables to Rust static data: rust/data/*.rs and
-- rust/crates/flash-cjk-core/src/data/*.rs. Run: nvim -l scripts/export_rs.lua
-- Single source of truth: the Lua modules themselves (defaults only).

local function esc(s)
	return (s:gsub("[\\\"]", { ['\\'] = '\\\\', ['"'] = '\\"' }))
end

local function write_file(path, lines)
	local f = io.open(path, "w")
	f:write(table.concat(lines, "\n"))
	f:write("\n")
	f:close()
	print("wrote " .. path)
end

local rust_escape = function(c)
	if c == "\\" then
		return "\\\\"
	end
	return c
end

-- ---------------------------------------------------------------- zhcn data
local zhcn = require("flash-cjk.zhcnData")

local function table_entries(t)
	local keys = {}
	for k in pairs(t) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	local out = {}
	for _, k in ipairs(keys) do
		local v = t[k]
		-- "[chars]" -> inner chars, escaped for Rust
		local inner = v:sub(2, -2)
		out[#out + 1] = string.format('("%s", "%s")', esc(k), esc(inner))
	end
	return out
end

write_file("rust/data/flypy.rs", {
	"// AUTO-GENERATED by scripts/export_rs.lua from lua/flash-cjk/zhcnData.lua -- DO NOT EDIT",
	"// Keys are 1-2 letter flypy codes; values are raw character-set strings.",
	"pub static CN_CHAR1: &[(&str, &str)] = &[",
	table.concat(table_entries(zhcn.char1patterns), ",\n"),
	"];",
	"",
	"pub static CN_CHAR2: &[(&str, &str)] = &[",
	table.concat(table_entries(zhcn.char2patterns), ",\n"),
	"];",
})

