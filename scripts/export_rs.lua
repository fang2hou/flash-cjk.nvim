-- ---------------------------------------------------------------- ko
local ko = require("flash-cjk.ko")
local jamo = ko.jamo

local function rust_str(v)
	return '"' .. esc(v) .. '"'
end

local ko_lines = {
	"// AUTO-GENERATED by scripts/export_rs.lua from lua/flash-cjk/ko.lua -- DO NOT EDIT",
	"// Korean jamo tables, index-aligned by 0-based L/V/T (None marks the",
	"// tense shift jamo that plain lowercase typing cannot produce).",
	"",
	string.format("pub static KO_L_ROMA: [&[&str]; %d] = [", #jamo.l_roma),
}
for _, romas in ipairs(jamo.l_roma) do
	local parts = {}
	for _, r in ipairs(romas) do
		parts[#parts + 1] = rust_str(r)
	end
	ko_lines[#ko_lines + 1] = "    &[" .. table.concat(parts, ", ") .. "],"
end
ko_lines[#ko_lines + 1] = "];"

local function ko_flat(name, arr)
	ko_lines[#ko_lines + 1] = ""
	ko_lines[#ko_lines + 1] = string.format("pub static %s: [&str; %d] = [", name, #arr)
	for _, v in ipairs(arr) do
		ko_lines[#ko_lines + 1] = "    " .. rust_str(v) .. ","
	end
	ko_lines[#ko_lines + 1] = "];"
end
ko_flat("KO_V_ROMA", jamo.v_roma)
ko_flat("KO_T_ROMA", jamo.t_roma)

-- Key tables are 0-based (index-aligned with the roma arrays above);
-- the roma lengths are the authority, since # on holed arrays is a border.
local function ko_opts(name, keys, n)
	ko_lines[#ko_lines + 1] = ""
	ko_lines[#ko_lines + 1] = string.format("pub static %s: [Option<&str>; %d] = [", name, n)
	for i = 0, n - 1 do
		local v = keys[i]
		ko_lines[#ko_lines + 1] = "    " .. (v and ("Some(" .. rust_str(v) .. ")") or "None") .. ","
	end
	ko_lines[#ko_lines + 1] = "];"
end
ko_opts("KO_L_KEYS", jamo.l_keys, #jamo.l_roma)
ko_opts("KO_V_KEYS", jamo.v_keys, #jamo.v_roma)
ko_opts("KO_T_KEYS", jamo.t_keys, #jamo.t_roma)

write_file("rust/crates/flash-cjk-core/src/data/ko.rs", ko_lines)

-- ---------------------------------------------------------------- punct
-- Punctuation classes per language: vim collection "[chars]" -> the
-- inner chars (backslash escapes kept; the Rust side strips them).
local function punct_entries(t)
	local keys = {}
	for k in pairs(t) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	local out = {}
	for _, k in ipairs(keys) do
		out[#out + 1] = string.format('("%s", "%s")', esc(k), esc(t[k]:sub(2, -2)))
	end
	return out
end

write_file("rust/crates/flash-cjk-core/src/data/punct.rs", {
	"// AUTO-GENERATED by scripts/export_rs.lua from lua/flash-cjk/zhcnData.lua and",
	"// lua/flash-cjk/ja.lua -- DO NOT EDIT",
	"// Punctuation keys -> matched characters per language.",
	"",
	"pub static PUNCT_CN: &[(&str, &str)] = &[",
	table.concat(punct_entries(zhcn.comma), ",\n"),
	"];",
	"",
	"pub static PUNCT_JP: &[(&str, &str)] = &[",
	table.concat(punct_entries(require("flash-cjk.ja").comma), ",\n"),
	"];",
})
