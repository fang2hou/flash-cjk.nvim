-- p3 values may be "[class]" or "\(class\|literal\|literal\)":
-- split into the class part and the literal two-char alternatives.
local function p3_entries(t)
	local keys = {}
	for k in pairs(t) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	local classes, literals = {}, {}
	for _, k in ipairs(keys) do
		local v = t[k]
		if v:sub(1, 2) == "\\(" then
			local body = v:sub(3, -3)
			local parts = vim.split(body, "\\|", { plain = true })
			for _, part in ipairs(parts) do
				if part:sub(1, 1) == "[" then
					classes[#classes + 1] = string.format('("%s", "%s")', esc(k), esc(part:sub(2, -2)))
				else
					literals[#literals + 1] = string.format('("%s", "%s")', esc(k), esc(part))
				end
			end
		else
			classes[#classes + 1] = string.format('("%s", "%s")', esc(k), esc(v:sub(2, -2)))
		end
	end
	return classes, literals
end

local p3_classes, p3_literals = p3_entries(ja_data.p3)

-- readings for labeler prediction (char -> comma-separated spellings)
local function readings_entries(t)
	local keys = {}
	for k in pairs(t) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	local out = {}
	for _, k in ipairs(keys) do
		out[#out + 1] = string.format('("%s", "%s")', esc(k), esc(table.concat(t[k], ",")))
	end
	return out
end

